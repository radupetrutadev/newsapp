// Generates supabase/seed.sql from the mock data in src/lib/mock, so a fresh
// Supabase project shows the same content as demo mode.
//
//   node scripts/generate-seed.mjs
//
// Requires Node 22.18+ (loads the .ts mock files with built-in type stripping).

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { mockArticles } from "../src/lib/mock/articles.ts";
import { mockTrends } from "../src/lib/mock/community.ts";
import { mockSources } from "../src/lib/mock/sources.ts";

const text = (value) => (value === null || value === undefined ? "null" : `'${String(value).replaceAll("'", "''")}'`);
const textArray = (values) => (values.length ? `array[${values.map(text).join(", ")}]` : "'{}'::text[]");
const row = (values) => `  (${values.join(", ")})`;

const sourceHandles = new Map(mockSources.map((source) => [source.id, source.handle]));

const sources = mockSources.map((source) =>
  row([
    text(source.handle),
    text(source.name),
    text(source.description),
    text(source.website),
    text(source.category),
    text(source.color),
    source.verified,
    source.followersCount,
    `${text(source.joinedAt)}::timestamptz`,
  ]),
);

const articles = mockArticles.map((article) =>
  row([
    text(article.slug),
    `(select id from public.sources where handle = ${text(sourceHandles.get(article.sourceId))})`,
    text(article.title),
    text(article.summary),
    textArray(article.body),
    text(article.category),
    textArray(article.tags),
    article.isBreaking,
    article.readTimeMinutes,
    article.stats.comments,
    article.stats.reposts,
    article.stats.likes,
    article.stats.views,
    `now() - interval '${article.minutesAgo} minutes'`,
  ]),
);

const trends = mockTrends.map((trend, index) =>
  row([text(trend.context), text(trend.topic), trend.postsCount, text(trend.category), index]),
);

const sql = `-- Generated by scripts/generate-seed.mjs from src/lib/mock. Do not edit by hand.

insert into public.sources (handle, name, description, website, category, color, verified, followers_count, created_at) values
${sources.join(",\n")}
on conflict (handle) do nothing;

insert into public.articles (slug, source_id, title, summary, body, category, tags, is_breaking, read_time_minutes, comments_count, reposts_count, likes_count, views_count, published_at) values
${articles.join(",\n")}
on conflict (slug) do nothing;

insert into public.trends (context, topic, posts_count, category, position) values
${trends.join(",\n")};
`;

const out = fileURLToPath(new URL("../supabase/seed.sql", import.meta.url));
writeFileSync(out, sql);
console.log(`Wrote ${mockSources.length} sources, ${mockArticles.length} articles and ${mockTrends.length} trends to supabase/seed.sql`);
